export function letter(n: number): Letter {
  const l = LETTERS.find((it) => it.n === n);
  if (!l) throw new Error(`no letter ${n}`);
  return l;
}

/** The text in the form for the reader: the player's letters change their address by gender. */
export function letterText(n: number, gender: Gender): string {
  const l = letter(n);
  return gender === 'f' && l.textF ? l.textF : l.text;
}

/** The letters that come to someone in a given chill. */
export function lettersFor(to: string, cycle: 1 | 2 | 3): Letter[] {
  return LETTERS.filter((l) => l.to === to && l.cycle === cycle);
}

